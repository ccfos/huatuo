# Exercise installation and cache recovery without downloading or loading Python.
set -euo pipefail
source "${ROOT_DIR}/integration/lib.sh"
require_commands tar gzip sha256sum awk find sort xargs cmp tr

readonly BUNDLE_FIXTURE="${HUATUO_BAMAI_TEST_TMPDIR}/bundle-fixture"
readonly BUNDLE_SOURCE="${BUNDLE_FIXTURE}/memray"
readonly BUNDLE_OUTPUT="${HUATUO_BAMAI_TEST_TMPDIR}/installed memray"
readonly BUNDLE_ARCHIVE="${HUATUO_BAMAI_TEST_TMPDIR}/memray-fixture.tar.gz"
readonly OFFLINE_BIN="${HUATUO_BAMAI_TEST_TMPDIR}/offline-bin"
mkdir -p "${BUNDLE_SOURCE}" "${OFFLINE_BIN}"
printf '{"schema_version":1}\n' > "${BUNDLE_SOURCE}/manifest.json"
for version in 3.7 3.8 3.9 3.10 3.11 3.12 3.13 3.14; do
	runtime="${BUNDLE_SOURCE}/runtimes/py${version}"
	mkdir -p "${runtime}/python/memray/"{commands,_ipython} "${runtime}/python/__pycache__"
	printf '{"python_version":"%s"}\n' "${version}" > "${runtime}/runtime.json"
	for file in __init__.py _metadata.py _version.py _ipython/__init__.py commands/_attach.gdb commands/_attach.lldb; do
		printf '# fixture for Python %s\n' "${version}" > "${runtime}/python/memray/${file}"
	done
	# Fake shared objects exercise installation/recovery, not ELF or ABI validity.
	printf 'extension fixture\n' > "${runtime}/python/memray/_memray.fixture.so"
	printf 'injector fixture\n' > "${runtime}/python/memray/_inject.fixture.so"
	printf '# vendored dependency fixture\n' > "${runtime}/python/dependency.py"
	printf 'packaged bytecode fixture\n' > "${runtime}/python/__pycache__/dependency.cpython.pyc"
	: > "${runtime}/python/memray/py.typed"
done
tar -czf "${BUNDLE_ARCHIVE}" -C "${BUNDLE_FIXTURE}" memray
bundle_sha256=$(sha256sum "${BUNDLE_ARCHIVE}" | awk '{print $1}')
readonly bundle_sha256
cat > "${OFFLINE_BIN}/curl" << 'EOF'
#!/usr/bin/env bash
echo 'unexpected network download in offline bundle test' >&2
exit 1
EOF
chmod +x "${OFFLINE_BIN}/curl"

assert_bundle_install() {
	local label=$1 expected_status=$2 archive=$3 checksum=$4 status=0
	local log="${HUATUO_BAMAI_TEST_TMPDIR}/${label}.log"
	PATH="${OFFLINE_BIN}:${PATH}" MEMRAY_BUNDLE_VERSION=fixture \
		MEMRAY_BUNDLE_ARCHITECTURE=x86_64 MEMRAY_BUNDLE_ARCHIVE="${archive}" \
		MEMRAY_BUNDLE_SHA256="${checksum}" \
		bash "${ROOT_DIR}/build/fetch-memray-bundle.sh" "${BUNDLE_OUTPUT}" \
		> "${log}" 2>&1 || status=$?
	if [[ ${status} != "${expected_status}" ]]; then
		cat "${log}" >&2
		fatal "${label}: installer exit=${status}, expected ${expected_status}"
	fi
}

assert_bundle_install initial 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
[[ $(< "${BUNDLE_OUTPUT}/.bundle-sha256") == "${bundle_sha256}" ]] \
	|| fatal "installer did not record the verified archive checksum"
# A complete cache must not read the archive or contact the network.
assert_bundle_install cache_hit 0 "${BUNDLE_ARCHIVE}.missing" "${bundle_sha256}"
grep -q 'already installed' "${HUATUO_BAMAI_TEST_TMPDIR}/cache_hit.log" \
	|| fatal "complete bundle was not accepted as a cache hit"

# Python can regenerate, add or remove bytecode without changing shipped code.
bytecode="${BUNDLE_OUTPUT}/runtimes/py3.12/python/__pycache__/dependency.cpython.pyc"
printf 'regenerated bytecode\n' > "${bytecode}"
printf 'optimized bytecode\n' > "${bytecode%.pyc}.opt-1.pyc"
assert_bundle_install regenerated_bytecode 0 "${BUNDLE_ARCHIVE}.missing" "${bundle_sha256}"
mv "${bytecode}" "${HUATUO_BAMAI_TEST_TMPDIR}/old-bytecode"
assert_bundle_install removed_bytecode 0 "${BUNDLE_ARCHIVE}.missing" "${bundle_sha256}"

# Same-size, nonempty changes must not be accepted as complete cache hits.
for path in manifest.json runtimes/py3.12/runtime.json \
	runtimes/py3.12/python/memray/_memray.fixture.so \
	runtimes/py3.12/python/memray/_inject.fixture.so \
	runtimes/py3.12/python/memray/_metadata.py \
	runtimes/py3.12/python/memray/commands/_attach.gdb \
	runtimes/py3.12/python/dependency.py; do
	label="changed-${path//\//-}"
	tr '[:lower:]' '[:upper:]' < "${BUNDLE_SOURCE}/${path}" > "${BUNDLE_OUTPUT}/${path}"
	assert_bundle_install "${label}" 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
	grep -q 'file contents or inventory have changed' "${HUATUO_BAMAI_TEST_TMPDIR}/${label}.log" \
		|| fatal "${label}: cache content changes were not identified"
	cmp "${BUNDLE_SOURCE}/${path}" "${BUNDLE_OUTPUT}/${path}" \
		|| fatal "${label}: installer did not restore the changed file"
done
printf '# unexpected module\n' > "${BUNDLE_OUTPUT}/runtimes/py3.12/python/unexpected.py"
assert_bundle_install extra_file 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
[[ ! -e "${BUNDLE_OUTPUT}/runtimes/py3.12/python/unexpected.py" ]] \
	|| fatal "installer retained an extra runtime module"
printf 'invalid checksum manifest\n' > "${BUNDLE_OUTPUT}/.bundle-checksums"
assert_bundle_install changed_checksums 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"

for version in 3.7 3.8 3.9 3.10 3.11 3.12 3.13 3.14; do
	for file in runtime.json python/memray/_memray.fixture.so python/memray/_inject.fixture.so; do
		path="runtimes/py${version}/${file}"
		label="missing-${version}-${file//\//-}"
		mv "${BUNDLE_OUTPUT}/${path}" "${HUATUO_BAMAI_TEST_TMPDIR}/${label}"
		assert_bundle_install "${label}" 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
		cmp "${BUNDLE_SOURCE}/${path}" "${BUNDLE_OUTPUT}/${path}" \
			|| fatal "${label}: installer did not restore the missing runtime file"
	done
done

for path in manifest.json runtimes/py3.12/python/dependency.py \
	runtimes/py3.12/python/memray/__init__.py runtimes/py3.12/python/memray/_metadata.py \
	runtimes/py3.12/python/memray/_version.py runtimes/py3.12/python/memray/_ipython/__init__.py \
	runtimes/py3.12/python/memray/commands/_attach.gdb runtimes/py3.12/python/memray/commands/_attach.lldb; do
	label="missing-${path//\//-}"
	mv "${BUNDLE_OUTPUT}/${path}" "${HUATUO_BAMAI_TEST_TMPDIR}/${label}"
	assert_bundle_install "${label}" 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
	cmp "${BUNDLE_SOURCE}/${path}" "${BUNDLE_OUTPUT}/${path}" \
		|| fatal "${label}: installer did not restore the missing package file"
done

mv "${BUNDLE_OUTPUT}/runtimes/py3.12" "${HUATUO_BAMAI_TEST_TMPDIR}/removed-runtime"
assert_bundle_install missing_runtime 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
cmp "${BUNDLE_SOURCE}/runtimes/py3.12/runtime.json" "${BUNDLE_OUTPUT}/runtimes/py3.12/runtime.json" \
	|| fatal "installer did not restore the missing runtime directory"
mv "${BUNDLE_OUTPUT}/.bundle-files" "${HUATUO_BAMAI_TEST_TMPDIR}/old-file-list"
assert_bundle_install missing_inventory 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
[[ -s "${BUNDLE_OUTPUT}/.bundle-files" ]] || fatal "installer did not rebuild the file list"
mv "${BUNDLE_OUTPUT}/.bundle-checksums" "${HUATUO_BAMAI_TEST_TMPDIR}/old-checksums"
assert_bundle_install missing_checksums 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
[[ -s "${BUNDLE_OUTPUT}/.bundle-checksums" ]] || fatal "installer did not rebuild the checksums"
: > "${BUNDLE_OUTPUT}/runtimes/py3.12/python/memray/_memray.fixture.so"
assert_bundle_install empty_extension 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
cmp "${BUNDLE_SOURCE}/runtimes/py3.12/python/memray/_memray.fixture.so" \
	"${BUNDLE_OUTPUT}/runtimes/py3.12/python/memray/_memray.fixture.so" \
	|| fatal "installer did not replace the empty extension"

# Source links are unsupported even when they stay inside the runtime tree.
for kind in relative-file absolute-file directory; do
	path=runtimes/py3.12/python/source-link
	target=dependency.py
	case "${kind}" in
	absolute-file) target="${BUNDLE_SOURCE}/runtimes/py3.12/python/dependency.py" ;;
	directory) target=memray ;;
	esac
	ln -s "${target}" "${BUNDLE_OUTPUT}/${path}"
	assert_bundle_install "repair-link-${kind}" 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
	[[ ! -L "${BUNDLE_OUTPUT}/${path}" ]] || fatal "cache recovery retained a source link"
	grep -q 'unsupported file in Memray bundle' "${HUATUO_BAMAI_TEST_TMPDIR}/repair-link-${kind}.log" \
		|| fatal "cache recovery did not identify the unsupported source link"

	ln -s "${target}" "${BUNDLE_SOURCE}/${path}"
	archive="${HUATUO_BAMAI_TEST_TMPDIR}/link-${kind}.tar.gz"
	tar -czf "${archive}" -C "${BUNDLE_FIXTURE}" memray
	checksum=$(sha256sum "${archive}" | awk '{print $1}')
	printf 'keep previous installation\n' > "${BUNDLE_OUTPUT}/keep-existing"
	assert_bundle_install "reject-link-${kind}" 1 "${archive}" "${checksum}"
	grep -q 'unsupported file in Memray bundle' "${HUATUO_BAMAI_TEST_TMPDIR}/reject-link-${kind}.log" \
		|| fatal "linked archive failed for an unrelated reason"
	[[ $(< "${BUNDLE_OUTPUT}/.bundle-sha256") == "${bundle_sha256}" &&
	$(< "${BUNDLE_OUTPUT}/keep-existing") == 'keep previous installation' ]] \
		|| fatal "linked archive replaced the previous installation"
	unlink "${BUNDLE_SOURCE}/${path}"
done

# Invalid replacements must leave the previous installation in place.
printf 'keep previous installation\n' > "${BUNDLE_OUTPUT}/keep-existing"
mv "${BUNDLE_OUTPUT}/runtimes/py3.12/python/memray/_inject.fixture.so" \
	"${HUATUO_BAMAI_TEST_TMPDIR}/removed-injector"
assert_bundle_install wrong_checksum 1 "${BUNDLE_ARCHIVE}" invalid
grep -q 'checksum mismatch' "${HUATUO_BAMAI_TEST_TMPDIR}/wrong_checksum.log" \
	|| fatal "invalid archive checksum failed for an unrelated reason"
mv "${BUNDLE_SOURCE}/runtimes/py3.12/python/memray/_inject.fixture.so" \
	"${HUATUO_BAMAI_TEST_TMPDIR}/source-injector"
tar -czf "${HUATUO_BAMAI_TEST_TMPDIR}/incomplete.tar.gz" -C "${BUNDLE_FIXTURE}" memray
incomplete_sha256=$(sha256sum "${HUATUO_BAMAI_TEST_TMPDIR}/incomplete.tar.gz" | awk '{print $1}')
assert_bundle_install incomplete_archive 1 "${HUATUO_BAMAI_TEST_TMPDIR}/incomplete.tar.gz" "${incomplete_sha256}"
grep -q 'one extension and one injector' "${HUATUO_BAMAI_TEST_TMPDIR}/incomplete_archive.log" \
	|| fatal "incomplete archive failed for an unrelated reason"
[[ $(< "${BUNDLE_OUTPUT}/.bundle-sha256") == "${bundle_sha256}" &&
$(< "${BUNDLE_OUTPUT}/keep-existing") == 'keep previous installation' ]] \
	|| fatal "failed installation replaced the previous bundle"
assert_bundle_install recover_after_failure 0 "${BUNDLE_ARCHIVE}" "${bundle_sha256}"
[[ ! -e "${BUNDLE_OUTPUT}/keep-existing" ]] || fatal "recovery retained the previous installation"
log_info "offline Memray bundle cache and recovery checks passed"
