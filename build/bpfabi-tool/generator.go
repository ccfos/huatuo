type mergedType struct {
	cName      string
	goName     string
	typ        btf.Type
	objectPath string
	canonical  string
}

func run(root string) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return fmt.Errorf("resolve repository root: %w", err)
	}
	domains, err := discoverDomains(root)
	if err != nil {
		return err
	}
	candidates, err := discoverCandidates(root, domains)
	if err != nil {
		return err
	}

	outputs := make(map[string][]byte, len(domains))
	goNames := make(map[string]string)
	for _, d := range domains {
		types, err := mergeCandidates(candidates[d.name])
		if err != nil {
			return fmt.Errorf("domain %q: %w", d.name, err)
		}
		if err := recordGoNames(goNames, types); err != nil {
			return err
		}
		output, err := generateDomain(types)
		if err != nil {
			return fmt.Errorf("generate domain %q: %w", d.name, err)
		}
		outputs[d.outputPath] = output
	}

	if err := ensureOutputDir(root); err != nil {
		return err
	}
	if err := replaceOutputs(outputs); err != nil {
		return err
	}
	return cleanStale(root, outputs)
}

func recordGoNames(names map[string]string, types []mergedType) error {
	for _, typ := range types {
		if previous, ok := names[typ.goName]; ok && previous != typ.cName {
			return fmt.Errorf(
				"go type name %q collides for c types %q and %q",
				typ.goName,
				previous,
				typ.cName,
			)
		}
		names[typ.goName] = typ.cName
	}
	return nil
}

func mergeCandidates(candidates []candidate) ([]mergedType, error) {
	byName := make(map[string]mergedType)
	for _, candidate := range candidates {
		if err := validateType(candidate.objectPath, candidate.cName, candidate.typ); err != nil {
			return nil, err
		}
		canonical, err := canonicalType(candidate.typ, make(map[btf.Type]bool))
		if err != nil {
			return nil, fmt.Errorf(
				"object %q type %q: %w",
				candidate.objectPath,
				candidate.cName,
				err,
			)
		}
		if previous, ok := byName[candidate.cName]; ok {
			if previous.canonical != canonical {
				return nil, fmt.Errorf(
					"type %q differs between objects %q and %q",
					candidate.cName,
					previous.objectPath,
					candidate.objectPath,
				)
			}
			continue
		}
		byName[candidate.cName] = mergedType{
			cName:      candidate.cName,
			goName:     goName(candidate.cName),
			typ:        candidate.typ,
			objectPath: candidate.objectPath,
			canonical:  canonical,
		}
	}

	types := make([]mergedType, 0, len(byName))
	for _, typ := range byName {
		types = append(types, typ)
	}
	sort.Slice(types, func(i, j int) bool {
		return types[i].cName < types[j].cName
	})
	return types, nil
}

func generateDomain(types []mergedType) ([]byte, error) {
	names := make(map[btf.Type]string, len(types))
	for _, typ := range types {
		names[stripQualifiers(typ.typ)] = typ.goName
	}
	formatter := btf.GoFormatter{
		Names:      names,
		Identifier: goName,
	}

	var out strings.Builder
	out.WriteString(generatedHeader)
	for _, typ := range types {
		declaration, err := formatter.TypeDeclaration(typ.goName, typ.typ)
		if err != nil {
			return nil, fmt.Errorf("format type %q from %q: %w", typ.cName, typ.objectPath, err)
		}
		out.WriteString(declaration)
		out.WriteString("\n\n")

		size, err := btf.Sizeof(typ.typ)
		if err != nil {
			return nil, fmt.Errorf("size type %q from %q: %w", typ.cName, typ.objectPath, err)
		}
		fmt.Fprintf(&out, "const %sSize = %d\n\n", typ.goName, size)
		out.WriteString("var (\n")
		fmt.Fprintf(
			&out,
			"_ [%sSize]byte = [unsafe.Sizeof(%s{})]byte{}\n",
			typ.goName,
			typ.goName,
		)

		strct, ok := stripQualifiers(typ.typ).(*btf.Struct)
		if ok {
			for _, member := range strct.Members {
				fmt.Fprintf(
					&out,
					"_ [%s]byte = [unsafe.Offsetof(%s{}.%s)]byte{}\n",
					offsetLiteral(member.Offset),
					typ.goName,
					goName(member.Name),
				)
			}
		}
		out.WriteString(")\n\n")
	}

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated go: %w", err)
	}
	return formatted, nil
}

func replaceOutputs(outputs map[string][]byte) error {
	paths := make([]string, 0, len(outputs))
	for path := range outputs {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	temps := make(map[string]string, len(paths))
	defer func() {
		for _, temp := range temps {
			_ = os.Remove(temp)
		}
	}()

	for _, path := range paths {
		temp, err := os.CreateTemp(filepath.Dir(path), ".bpfabi-tool-*")
		if err != nil {
			return fmt.Errorf("create temporary output for %q: %w", path, err)
		}
		tempPath := temp.Name()
		temps[path] = tempPath

		if _, err := temp.Write(outputs[path]); err != nil {
			_ = temp.Close()
			return fmt.Errorf("write temporary output for %q: %w", path, err)
		}
		if err := temp.Chmod(0o644); err != nil {
			_ = temp.Close()
			return fmt.Errorf("set mode on temporary output for %q: %w", path, err)
		}
		if err := temp.Close(); err != nil {
			return fmt.Errorf("close temporary output for %q: %w", path, err)
		}
	}

	for _, path := range paths {
		if existing, err := os.ReadFile(path); err == nil && bytes.Equal(existing, outputs[path]) {
			if err := os.Remove(temps[path]); err != nil {
				return fmt.Errorf("remove unchanged temporary output for %q: %w", path, err)
			}
			delete(temps, path)
			continue
		}
		if err := os.Rename(temps[path], path); err != nil {
			return fmt.Errorf("replace generated output %q: %w", path, err)
		}
		delete(temps, path)
	}
	return nil
}

func cleanStale(root string, outputs map[string][]byte) error {
	dir := filepath.Join(root, "internal", "bpf", "abi")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read output directory %q: %w", dir, err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), "_types_generated.go") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		if _, ok := outputs[path]; ok {
			continue
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read stale candidate %q: %w", path, err)
		}
		if !bytes.Contains(content, []byte(generatedMarker)) &&
			!bytes.Contains(content, []byte(legacyGeneratedMarker)) {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("remove stale generated output %q: %w", path, err)
		}
	}
	return nil
}
