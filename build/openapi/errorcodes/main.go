var errorCodePattern = regexp.MustCompile(`^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$`)

type definition struct {
	Code        string
	HTTPStatus  int
	Description string
}

type catalog struct {
	name        string
	packageName string
	specPath    string
	outputDir   string
	definitions []definition
}

func main() {
	var specRoot string
	var outputRoot string
	flag.StringVar(&specRoot, "spec-root", ".", "repository root containing apis/v1")
	flag.StringVar(&outputRoot, "output-root", ".", "root directory for generated files")
	flag.Parse()

	if err := run(specRoot, outputRoot); err != nil {
		fmt.Fprintf(os.Stderr, "generate OpenAPI error codes: %v\n", err)
		os.Exit(1)
	}
}

func run(specRoot, outputRoot string) error {
	catalogs := []catalog{
		{
			name:        "common",
			packageName: "v1",
			specPath:    filepath.Join(specRoot, "apis/v1/components.yaml"),
			outputDir:   filepath.Join(outputRoot, "apis/v1"),
		},
		{
			name:        "server",
			packageName: "server",
			specPath:    filepath.Join(specRoot, "apis/v1/server/openapi.yaml"),
			outputDir:   filepath.Join(outputRoot, "apis/v1/server"),
		},
		{
			name:        "node",
			packageName: "node",
			specPath:    filepath.Join(specRoot, "apis/v1/node/openapi.yaml"),
			outputDir:   filepath.Join(outputRoot, "apis/v1/node"),
		},
	}

	for i := range catalogs {
		data, err := os.ReadFile(catalogs[i].specPath)
		if err != nil {
			return fmt.Errorf("read %s catalog %q: %w", catalogs[i].name, catalogs[i].specPath, err)
		}
		definitions, err := parseCatalog(data)
		if err != nil {
			return fmt.Errorf("parse %s catalog %q: %w", catalogs[i].name, catalogs[i].specPath, err)
		}
		catalogs[i].definitions = definitions
	}
	if err := validateCatalogs(catalogs); err != nil {
		return err
	}

	for i := range catalogs {
		current := &catalogs[i]
		codes, err := generateCodes(current)
		if err != nil {
			return err
		}
		if err := writeGeneratedFile(filepath.Join(current.outputDir, "error_codes.gen.go"), codes); err != nil {
			return err
		}

		statuses, err := generateHTTPStatuses(current)
		if err != nil {
			return err
		}
		if err := writeGeneratedFile(filepath.Join(current.outputDir, "http_status.gen.go"), statuses); err != nil {
			return err
		}
	}

	return nil
}

func parseCatalog(data []byte) ([]definition, error) {
	var document yaml.Node
	if err := yaml.Unmarshal(data, &document); err != nil {
		return nil, fmt.Errorf("decode YAML: %w", err)
	}
	if len(document.Content) != 1 || document.Content[0].Kind != yaml.MappingNode {
		return nil, errors.New("OpenAPI document must be a mapping")
	}

	errorCodes, err := uniqueMappingValue(document.Content[0], "x-error-codes")
	if err != nil {
		return nil, err
	}
	if errorCodes == nil {
		return nil, errors.New("x-error-codes is required")
	}
	if errorCodes.Kind != yaml.MappingNode {
		return nil, errors.New("x-error-codes must be a mapping")
	}

	definitions := make([]definition, 0, len(errorCodes.Content)/2)
	seen := make(map[string]struct{}, len(errorCodes.Content)/2)
	for i := 0; i < len(errorCodes.Content); i += 2 {
		code := errorCodes.Content[i].Value
		if _, ok := seen[code]; ok {
			return nil, fmt.Errorf("duplicate error code %q", code)
		}
		seen[code] = struct{}{}
		if !errorCodePattern.MatchString(code) {
			return nil, fmt.Errorf("error code %q must use lower snake_case", code)
		}

		entry, err := parseDefinition(code, errorCodes.Content[i+1])
		if err != nil {
			return nil, err
		}
		definitions = append(definitions, entry)
	}

	sort.Slice(definitions, func(i, j int) bool {
		return definitions[i].Code < definitions[j].Code
	})
	return definitions, nil
}

func parseDefinition(code string, node *yaml.Node) (definition, error) {
	if node.Kind != yaml.MappingNode {
		return definition{}, fmt.Errorf("error code %q definition must be a mapping", code)
	}

	var result definition
	result.Code = code
	seen := make(map[string]struct{}, len(node.Content)/2)
	for i := 0; i < len(node.Content); i += 2 {
		field := node.Content[i].Value
		if _, ok := seen[field]; ok {
			return definition{}, fmt.Errorf("error code %q has duplicate field %q", code, field)
		}
		seen[field] = struct{}{}

		value := node.Content[i+1]
		switch field {
		case "httpStatus":
			status, err := strconv.Atoi(value.Value)
			if err != nil {
				return definition{}, fmt.Errorf("error code %q httpStatus must be an integer", code)
			}
			result.HTTPStatus = status
		case "description":
			result.Description = strings.TrimSpace(value.Value)
		default:
			return definition{}, fmt.Errorf("error code %q has unsupported field %q", code, field)
		}
	}

	if result.HTTPStatus < 400 || result.HTTPStatus > 599 {
		return definition{}, fmt.Errorf(
			"error code %q httpStatus %d must be between 400 and 599",
			code,
			result.HTTPStatus,
		)
	}
	if result.Description == "" {
		return definition{}, fmt.Errorf("error code %q description is required", code)
	}
	return result, nil
}

func uniqueMappingValue(mapping *yaml.Node, key string) (*yaml.Node, error) {
	var result *yaml.Node
	for i := 0; i < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value != key {
			continue
		}
		if result != nil {
			return nil, fmt.Errorf("duplicate OpenAPI field %q", key)
		}
		result = mapping.Content[i+1]
	}
	return result, nil
}

func validateCatalogs(catalogs []catalog) error {
	type occurrence struct {
		catalogName string
		definition  definition
	}
	seen := make(map[string]occurrence)
	for _, current := range catalogs {
		for _, candidate := range current.definitions {
			previous, ok := seen[candidate.Code]
			if !ok {
				seen[candidate.Code] = occurrence{catalogName: current.name, definition: candidate}
				continue
			}
			if previous.definition.HTTPStatus != candidate.HTTPStatus ||
				previous.definition.Description != candidate.Description {
				return fmt.Errorf(
					"error code %q differs between %s and %s catalogs",
					candidate.Code,
					previous.catalogName,
					current.name,
				)
			}
		}
	}
	return nil
}

func generateCodes(current *catalog) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	fmt.Fprintf(&output, "package %s\n\n", current.packageName)
	if current.name == "common" {
		output.WriteString("// ErrorCode identifies a stable API error.\n")
		output.WriteString("type ErrorCode string\n\n")
	} else {
		output.WriteString("import apiv1 \"huatuo-bamai/apis/v1\"\n\n")
	}

	output.WriteString("const (\n")
	for _, item := range current.definitions {
		typeName := "ErrorCode"
		if current.name != "common" {
			typeName = "apiv1.ErrorCode"
		}
		fmt.Fprintf(
			&output,
			"\tErrorCode%s %s = %q\n",
			goName(item.Code),
			typeName,
			item.Code,
		)
	}
	output.WriteString(")\n")

	return formatGenerated(current.name+" error codes", output.Bytes())
}

func generateHTTPStatuses(current *catalog) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	fmt.Fprintf(&output, "package %s\n\n", current.packageName)
	if current.name != "common" {
		output.WriteString("import apiv1 \"huatuo-bamai/apis/v1\"\n\n")
	}

	codeType := "ErrorCode"
	if current.name != "common" {
		codeType = "apiv1.ErrorCode"
	}
	fmt.Fprintf(
		&output,
		"// HTTPStatusForErrorCode returns the default request-level HTTP status.\nfunc HTTPStatusForErrorCode(code %s) (int, bool) {\n",
		codeType,
	)
	if current.name != "common" {
		output.WriteString("\tif status, ok := apiv1.HTTPStatusForErrorCode(code); ok {\n")
		output.WriteString("\t\treturn status, true\n\t}\n\n")
	}
	output.WriteString("\tswitch code {\n")
	for _, item := range current.definitions {
		fmt.Fprintf(
			&output,
			"\tcase ErrorCode%s:\n\t\treturn %d, true\n",
			goName(item.Code),
			item.HTTPStatus,
		)
	}
	output.WriteString("\tdefault:\n\t\treturn 0, false\n\t}\n}\n")

	return formatGenerated(current.name+" HTTP statuses", output.Bytes())
}

func goName(code string) string {
	initialisms := map[string]string{
		"api":  "API",
		"cpu":  "CPU",
		"http": "HTTP",
		"id":   "ID",
		"io":   "IO",
		"tcp":  "TCP",
		"url":  "URL",
	}
	if code == "internal_error" {
		return "Internal"
	}
	parts := strings.Split(code, "_")
	for i, part := range parts {
		if initialism, ok := initialisms[part]; ok {
			parts[i] = initialism
			continue
		}
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

func formatGenerated(name string, source []byte) ([]byte, error) {
	formatted, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("format generated %s: %w", name, err)
	}
	return formatted, nil
}

func writeGeneratedFile(path string, data []byte) error {
	directory := filepath.Dir(path)
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return fmt.Errorf("create output directory %q: %w", directory, err)
	}

	temporary, err := os.CreateTemp(directory, ".error-codes-*.tmp")
	if err != nil {
		return fmt.Errorf("create temporary output for %q: %w", path, err)
	}
	temporaryPath := temporary.Name()
	defer os.Remove(temporaryPath)

	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return fmt.Errorf("write temporary output for %q: %w", path, err)
	}
	if err := temporary.Chmod(0o644); err != nil {
		temporary.Close()
		return fmt.Errorf("set output mode for %q: %w", path, err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close temporary output for %q: %w", path, err)
	}
	if err := os.Rename(temporaryPath, path); err != nil {
		return fmt.Errorf("replace generated output %q: %w", path, err)
	}
	return nil
}
